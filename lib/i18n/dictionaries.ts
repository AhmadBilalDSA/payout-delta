/**
 * PayoutDelta — decoupled global UI dictionary (Phase 7 refresh).
 *
 * A single flat catalog of UI strings — every copy string that follows the
 * visitor across routes — authored in seven languages and keyed off the
 * English catalog so the compiler statically guarantees all languages stay
 * complete and sandboxed: add a key to `enStrings` and TypeScript raises an
 * excess-property error on every catalog that has not translated it yet.
 *
 *   - `enStrings`     — canonical key set + English values (`UiKey` derives
 *                       from `keyof typeof enStrings`).
 *   - `DICTIONARIES`  — per-language `UiCatalog`; `isRTL` drives the
 *                       document `dir` attribute switch.
 *   - `LANG_META`     — display metadata for the header language switcher.
 *   - `Vars`          — interpolation values honored by the provider `t()`.
 *
 * Placeholders use `{curly}` names and are replaced verbatim, so every
 * language must preserve them exactly (the build will not translate runtime
 * numbers for you). Product names, provider identities, legal acronyms
 * (PSEB / PRC / FEMA / FIRC / LUT / VAT / GST / P2P) and corridor codes stay
 * English in every language under nominative fair use.
 */

