/**
 * Resolves the compliance guide for a corridor slug; unknown slugs fall back
 * to a complete generic record so the UI never renders an empty drawer.
 */
export function getComplianceGuide(slug: string): ComplianceGuide {
  return CORRIDOR_GUIDES[slug] ?? { ...DEFAULT_COMPLIANCE_GUIDE, slug };
}

/** True when the slug has a bespoke (country-specific) compliance record. */
export function hasComplianceGuide(slug: string): boolean {
  return Object.hasOwn(CORRIDOR_GUIDES, slug);
}

/** Corridor slugs with bespoke regulatory content (used by the audit script). */
export function getComplianceGuideSlugs(): string[] {
  return Object.keys(CORRIDOR_GUIDES);
}
