import type { FaqItem } from "@/lib/corridorContent";

/**
 * Phase 5 — Regional banking & tax compliance repository.
 *
 * One record per corridor slug maps the regulatory body, legal authority,
 * withholding/exemption schedule, mandatory documentation, domestic clearing
 * network and a step-by-step realization-certificate checklist. Slugs without
 * a bespoke record receive the generic `DEFAULT_COMPLIANCE_GUIDE` so every
 * corridor page can render a complete, non-empty drawer.
 *
 * All copy is hedged informational guidance — never financial or tax advice —
 * and mirrors the editorial standards used in `lib/corridorContent.ts`.
 */

export interface ComplianceTaxRow {
  /** Taxpayer / transaction status, e.g. "PSEB-registered exporter". */
  status: string;
  /** Effective rate or treatment. */
  rate: string;
  /** Statutory basis, e.g. "FBR Section 154A". */
  basis: string;
}

export interface ComplianceChecklistStep {
  title: string;
  detail: string;
}

export interface ComplianceWarning {
  title: string;
  body: string;
}

export interface ComplianceGuide {
  /** Corridor slug this guide is bound to (e.g. `usd-to-pkr`). */
  slug: string;
  /** Drawer headline, e.g. "Pakistan Freelance Remittance & PSEB Tax Guide". */
  title: string;
  country: string;
  /** Primary regulator, e.g. "State Bank of Pakistan (SBP) — FEOD". */
  regulatoryBody: string;
  /** Governing statute / framework line. */
  legalAuthority: string;
  /** Domestic clearing rail(s) for the receiving country. */
  clearingNetwork: string;
  /** Mandatory documentation for substantiating the inward remittance. */
  documentation: string[];
  /** Lead sentence for the withholding / exemption table. */
  taxIntro: string;
  taxRows: ComplianceTaxRow[];
  checklistTitle: string;
  checklistSteps: ComplianceChecklistStep[];
  warning: ComplianceWarning;
  /** Regulatory FAQs merged into the page FAQPage JSON-LD and accordion. */
  faqs: FaqItem[];
}

